
-- Create document templates table for storing reusable templates
CREATE TABLE public.document_templates (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  name TEXT NOT NULL,
  template_type TEXT NOT NULL CHECK (template_type IN ('permit_application', 'structural_report', 'technical_documentation', 'compliance_report', 'custom')),
  category TEXT NOT NULL, -- e.g., 'residential', 'commercial', 'industrial'
  description TEXT,
  template_content JSONB NOT NULL, -- Template structure with placeholders
  format_type TEXT NOT NULL CHECK (format_type IN ('pdf', 'docx', 'both')),
  variables JSONB NOT NULL DEFAULT '[]'::jsonb, -- Available variables for template
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_by UUID,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Create document exports table for tracking generated documents
CREATE TABLE public.document_exports (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  upload_id UUID REFERENCES public.blueprint_uploads(id) ON DELETE CASCADE,
  template_id UUID REFERENCES public.document_templates(id) ON DELETE SET NULL,
  document_type TEXT NOT NULL,
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'generating' CHECK (status IN ('generating', 'completed', 'failed', 'cancelled')),
  format_type TEXT NOT NULL CHECK (format_type IN ('pdf', 'docx')),
  file_path TEXT, -- Storage path for generated document
  file_size BIGINT,
  generation_data JSONB NOT NULL DEFAULT '{}'::jsonb, -- Data used for generation
  ai_generated_content JSONB, -- Content generated by Gemini AI
  error_message TEXT,
  generated_by UUID NOT NULL,
  generated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  completed_at TIMESTAMP WITH TIME ZONE
);

-- Create document variables table for dynamic content
CREATE TABLE public.document_variables (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  export_id UUID NOT NULL REFERENCES public.document_exports(id) ON DELETE CASCADE,
  variable_name TEXT NOT NULL,
  variable_value JSONB NOT NULL,
  data_source TEXT, -- e.g., 'bim_elements', 'compliance_violations', 'manual_input'
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Create indexes for better performance
CREATE INDEX idx_document_templates_type ON public.document_templates(template_type);
CREATE INDEX idx_document_templates_category ON public.document_templates(category);
CREATE INDEX idx_document_templates_active ON public.document_templates(is_active) WHERE is_active = true;

CREATE INDEX idx_document_exports_upload_id ON public.document_exports(upload_id);
CREATE INDEX idx_document_exports_template_id ON public.document_exports(template_id);
CREATE INDEX idx_document_exports_status ON public.document_exports(status);
CREATE INDEX idx_document_exports_generated_by ON public.document_exports(generated_by);

CREATE INDEX idx_document_variables_export_id ON public.document_variables(export_id);
CREATE INDEX idx_document_variables_name ON public.document_variables(variable_name);

-- Add triggers to update the updated_at timestamp
CREATE TRIGGER update_document_templates_updated_at
  BEFORE UPDATE ON public.document_templates
  FOR EACH ROW
  EXECUTE FUNCTION public.update_updated_at_column();

